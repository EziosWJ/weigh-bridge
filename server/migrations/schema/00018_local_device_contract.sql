-- +goose Up
-- ADR 0030 contract: Server-owned cameras, measurement generations, Agent
-- effective-config backups and runtime diagnostics. Existing business rows,
-- images and print attempts are preserved. Historical pairing identities are
-- retired in place, never deleted, because operators may still reference them
-- while investigating earlier device events.

CREATE TABLE wb_camera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    source_url TEXT NOT NULL DEFAULT '',
    username TEXT NOT NULL DEFAULT '',
    password TEXT NOT NULL DEFAULT '',
    capture_enabled SMALLINT NOT NULL DEFAULT 0 CHECK (capture_enabled IN (0,1)),
    enabled SMALLINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0,1)),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version>0),
    create_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE UNIQUE INDEX uk_wb_camera_name_active ON wb_camera (LOWER(name)) WHERE deleted=0;
CREATE INDEX idx_wb_camera_active ON wb_camera (deleted,capture_enabled,id);

-- One managed MediaMTX path per camera. Only rows in this table are touched by
-- Server; other streams in a shared MediaMTX instance are never scanned or
-- overwritten. Soft-deleted cameras keep their row until the remote path is
-- removed so an offline delete can be resumed without inventing a new stream.
CREATE TABLE wb_camera_stream (
    camera_id BIGINT PRIMARY KEY REFERENCES wb_camera(id) ON DELETE RESTRICT,
    media_path VARCHAR(120) NOT NULL UNIQUE,
    desired_version BIGINT NOT NULL DEFAULT 1 CHECK (desired_version>0),
    synced_version BIGINT NOT NULL DEFAULT 0 CHECK (synced_version>=0),
    state VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','synced','error','removing','removed')),
    last_error TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    synced_at TIMESTAMP WITH TIME ZONE,
    removed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_wb_camera_stream_state ON wb_camera_stream (state,updated_at);

-- Singleton camera/video settings. config_version changes when camera content
-- used by a capture changes; in-flight and unconfirmed samples freeze it.
-- video_version changes only for MediaMTX endpoint settings and may lag a
-- camera edit because remote availability is reported separately.
CREATE TABLE wb_camera_settings (
    id BIGINT PRIMARY KEY CHECK (id=1),
    config_version BIGINT NOT NULL DEFAULT 1 CHECK (config_version>0),
    capture_timeout_ms INTEGER NOT NULL DEFAULT 6000 CHECK (capture_timeout_ms BETWEEN 500 AND 60000),
    recognition_url TEXT NOT NULL DEFAULT '',
    recognition_camera_id BIGINT REFERENCES wb_camera(id) ON DELETE SET NULL,
    mediamtx_api_url TEXT NOT NULL DEFAULT '',
    mediamtx_api_username TEXT NOT NULL DEFAULT '',
    mediamtx_api_password TEXT NOT NULL DEFAULT '',
    mediamtx_whep_base_url TEXT NOT NULL DEFAULT '',
    video_version BIGINT NOT NULL DEFAULT 1 CHECK (video_version>0),
    video_sync_state VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (video_sync_state IN ('pending','synced','error')),
    video_sync_error TEXT NOT NULL DEFAULT '',
    video_synced_version BIGINT NOT NULL DEFAULT 0 CHECK (video_synced_version>=0),
    update_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- New Server-acquired images. Legacy Agent images remain files without a row;
-- the image reference is the compatibility boundary. Failed acquisitions are
-- stored with status=failed and no file so per-camera failure is auditable.
CREATE TABLE wb_weighing_image (
    id VARCHAR(80) PRIMARY KEY,
    scale_id BIGINT NOT NULL REFERENCES wb_scale(id) ON DELETE RESTRICT,
    camera_id BIGINT REFERENCES wb_camera(id) ON DELETE RESTRICT,
    camera_public_id VARCHAR(40) NOT NULL DEFAULT '',
    camera_name VARCHAR(100) NOT NULL DEFAULT '',
    camera_source TEXT NOT NULL DEFAULT '',
    source VARCHAR(20) NOT NULL CHECK (source IN ('server','agent')),
    view VARCHAR(20) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL CHECK (status IN ('captured','failed','missing')),
    error TEXT NOT NULL DEFAULT '',
    file_name TEXT NOT NULL DEFAULT '',
    sha256 VARCHAR(64) NOT NULL DEFAULT '',
    width INTEGER NOT NULL DEFAULT 0 CHECK (width>=0),
    height INTEGER NOT NULL DEFAULT 0 CHECK (height>=0),
    bytes BIGINT NOT NULL DEFAULT 0 CHECK (bytes>=0),
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    create_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_wb_image_scale_time ON wb_weighing_image(scale_id,captured_at,id);
CREATE INDEX idx_wb_image_camera_time ON wb_weighing_image(camera_id,captured_at,id);

-- Server copy of the last Agent-confirmed device settings. It is a recovery
-- source only, never a second editable configuration surface.
CREATE TABLE wb_agent_config_backup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scale_id BIGINT NOT NULL REFERENCES wb_scale(id) ON DELETE RESTRICT,
    config_version BIGINT NOT NULL CHECK (config_version>=0),
    digest VARCHAR(64) NOT NULL,
    settings JSONB NOT NULL,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source VARCHAR(20) NOT NULL DEFAULT 'auto' CHECK (source IN ('auto','restore')),
    restored_from_id BIGINT REFERENCES wb_agent_config_backup(id) ON DELETE RESTRICT,
    restore_requested_at TIMESTAMP WITH TIME ZONE,
    restored_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (scale_id,config_version,digest)
);
CREATE INDEX idx_wb_agent_backup_scale_time ON wb_agent_config_backup(scale_id,applied_at DESC,id DESC);

-- Persisted diagnostic and effective-config report. Online state still comes
-- from the live hub; host/IP/version are not pairing identities.
CREATE TABLE wb_agent_runtime (
    scale_id BIGINT PRIMARY KEY REFERENCES wb_scale(id) ON DELETE RESTRICT,
    public_id VARCHAR(80) NOT NULL DEFAULT '',
    protocol_version INTEGER NOT NULL DEFAULT 1 CHECK (protocol_version>=1),
    agent_version VARCHAR(60) NOT NULL DEFAULT '',
    hostname VARCHAR(255) NOT NULL DEFAULT '',
    remote_addr TEXT NOT NULL DEFAULT '',
    connected SMALLINT NOT NULL DEFAULT 0 CHECK (connected IN (0,1)),
    capabilities JSONB NOT NULL DEFAULT '[]'::jsonb,
    connected_at TIMESTAMP WITH TIME ZONE,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    effective_config_version BIGINT NOT NULL DEFAULT 0 CHECK (effective_config_version>=0),
    effective_config_digest VARCHAR(64) NOT NULL DEFAULT '',
    effective_settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    effective_applied_at TIMESTAMP WITH TIME ZONE,
    device_state VARCHAR(20) NOT NULL DEFAULT 'unknown',
    update_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The measurement generation survives the image window and must remain the
-- Agent's current basis at operator confirmation. Old rows stay valid with an
-- empty generation so historical samples keep their original rules.
ALTER TABLE wb_sample ADD COLUMN measurement_generation VARCHAR(80) NOT NULL DEFAULT '';
ALTER TABLE wb_sample ADD COLUMN measurement_verified_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE wb_sample ADD COLUMN camera_config_version BIGINT NOT NULL DEFAULT 0;
CREATE INDEX idx_wb_sample_measurement ON wb_sample(measurement_generation) WHERE measurement_generation<>'';

-- Retirement is in-place. The key values remain for historical investigation,
-- but no admission path treats them as authority after this migration.
ALTER TABLE wb_agent_binding ADD COLUMN retired_at TIMESTAMP WITH TIME ZONE;
UPDATE wb_agent_binding SET retired_at = COALESCE(retired_at,CURRENT_TIMESTAMP) WHERE retired_at IS NULL;

