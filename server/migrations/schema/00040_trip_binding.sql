-- Local authority for the trip <-> task <-> ticket relationship. A row is
-- created on the first weigh with the trip and laboratory snapshot, then
-- completed when the second weigh issues a ticket and when the cloud confirms
-- the ticket link.
CREATE TABLE wb_trip_binding (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 site_code VARCHAR(80) NOT NULL,
 trip_no VARCHAR(40) NOT NULL,
 cloud_trip_id BIGINT NOT NULL DEFAULT 0,
 trip_version BIGINT NOT NULL DEFAULT 0,
 plate VARCHAR(40) NOT NULL,
 material_code VARCHAR(80) NOT NULL,
 material_name VARCHAR(200) NOT NULL,
 party_code VARCHAR(80) NOT NULL,
 party_name VARCHAR(200) NOT NULL,
 task_id BIGINT NOT NULL UNIQUE REFERENCES wb_transport_task(id),
 ticket_id BIGINT UNIQUE REFERENCES wb_ticket(id),
 inspection_id BIGINT NOT NULL DEFAULT 0,
 inspection_version BIGINT NOT NULL DEFAULT 0,
 inspection_snapshot TEXT NOT NULL DEFAULT '',
 deduction_snapshot TEXT NOT NULL DEFAULT '',
 trip_snapshot TEXT NOT NULL DEFAULT '',
 cloud_ticket_no VARCHAR(80) NOT NULL DEFAULT '',
 status VARCHAR(20) NOT NULL DEFAULT 'bound' CHECK (status IN ('bound','ticketed','linked','conflict','superseded')),
 operation_id VARCHAR(128) NOT NULL DEFAULT '',
 created_by BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ticketed_at TIMESTAMPTZ,
 linked_at TIMESTAMPTZ,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_wb_trip_binding_active_trip ON wb_trip_binding(trip_no) WHERE status IN ('bound','ticketed','linked');
CREATE INDEX idx_wb_trip_binding_ticket ON wb_trip_binding(ticket_id) WHERE ticket_id IS NOT NULL;
CREATE INDEX idx_wb_trip_binding_status ON wb_trip_binding(status);

