-- Factory-side record of one mobile QR handoff. The cloud handoff is the
-- idempotency key; the task/ticket rows remain the normal factory records.
CREATE TABLE wb_mobile_handoff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  handoff_id BIGINT NOT NULL,
  weighing_id BIGINT NOT NULL,
  action VARCHAR(10) NOT NULL CHECK (action IN ('first', 'second')),
  site_code VARCHAR(40) NOT NULL,
  scale_code VARCHAR(40) NOT NULL,
  plate VARCHAR(20) NOT NULL,
  mobile_account VARCHAR(100) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'claimed',
  task_id BIGINT REFERENCES wb_transport_task(id),
  ticket_id BIGINT REFERENCES wb_ticket(id),
  first_record_id BIGINT,
  second_record_id BIGINT,
  result JSONB,
  error TEXT NOT NULL DEFAULT '',
  claimed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (handoff_id, action)
);
CREATE INDEX wb_mobile_handoff_recent ON wb_mobile_handoff (id DESC);
CREATE INDEX wb_mobile_handoff_plate ON wb_mobile_handoff (plate, id DESC);

