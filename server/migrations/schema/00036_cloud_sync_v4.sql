-- Digest-protocol outbox (schemaVersion 4). It is kept apart from the legacy
-- v2/v3 outbox so a ticket never mixes the two protocols and old queued
-- changes remain available unchanged.
CREATE TABLE wb_ticket_sync_change_v4 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES wb_ticket(id),
    previous_ticket_id BIGINT REFERENCES wb_ticket(id),
    digest CHAR(64) NOT NULL UNIQUE CHECK (digest ~ '^[0-9a-f]{64}$'),
    digest_version SMALLINT NOT NULL CHECK (digest_version >= 1),
    schema_version SMALLINT NOT NULL,
    site_code VARCHAR(40) NOT NULL,
    ticket_no VARCHAR(200) NOT NULL,
    change_type VARCHAR(10) NOT NULL CHECK (change_type IN ('issue','void','reopen')),
    payload TEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','waiting_predecessor','temporary_failure','needs_admin','conflict','synced')),
    category VARCHAR(24) NOT NULL DEFAULT '',
    reason_code VARCHAR(64) NOT NULL DEFAULT '',
    reason TEXT NOT NULL DEFAULT '',
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    last_attempt_at TIMESTAMPTZ,
    synced_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX wb_ticket_sync_change_v4_ticket ON wb_ticket_sync_change_v4(ticket_id, id);
CREATE INDEX wb_ticket_sync_change_v4_previous ON wb_ticket_sync_change_v4(previous_ticket_id);
CREATE INDEX wb_ticket_sync_change_v4_due ON wb_ticket_sync_change_v4(next_attempt_at, id) WHERE status <> 'synced';
CREATE INDEX wb_ticket_sync_change_v4_created ON wb_ticket_sync_change_v4(created_at);

-- Latest reconciliation result per ticket. A failed query is stored as
-- 'unknown' and must never be presented as consistent.
CREATE TABLE wb_ticket_reconcile (
    ticket_id BIGINT PRIMARY KEY REFERENCES wb_ticket(id),
    site_code VARCHAR(40) NOT NULL,
    ticket_no VARCHAR(200) NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('consistent','pending','needs_review','conflict','unknown')),
    cloud_found BOOLEAN,
    cloud_status VARCHAR(10),
    local_latest_digest CHAR(64),
    cloud_latest_digest CHAR(64),
    cloud_latest_digest_version SMALLINT,
    cloud_latest_change_type VARCHAR(10),
    cloud_received_at TIMESTAMPTZ,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    checked_at TIMESTAMPTZ NOT NULL,
    trigger_type VARCHAR(10) NOT NULL CHECK (trigger_type IN ('manual','automatic'))
);
CREATE INDEX wb_ticket_reconcile_checked ON wb_ticket_reconcile(checked_at DESC);

-- Conflict and handling records are separate from ordinary attempt logs so
-- clearing logs never removes a conclusion or a pending difference.
CREATE TABLE wb_ticket_sync_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES wb_ticket(id),
    digest CHAR(64) NOT NULL DEFAULT '',
    reason_code VARCHAR(64) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')),
    blocking BOOLEAN NOT NULL DEFAULT FALSE,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    conclusion TEXT NOT NULL DEFAULT '',
    concluded_by BIGINT REFERENCES sys_user(id),
    concluded_by_name VARCHAR(100) NOT NULL DEFAULT '',
    concluded_at TIMESTAMPTZ,
    last_checked_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (ticket_id, digest, reason_code)
);
CREATE INDEX wb_ticket_sync_review_open ON wb_ticket_sync_review(ticket_id) WHERE status = 'open';

-- Automatic reconciliation bookkeeping: one row per local database.
CREATE TABLE wb_sync_reconcile_state (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    last_auto_date DATE,
    last_auto_success BOOLEAN NOT NULL DEFAULT FALSE,
    last_run_at TIMESTAMPTZ,
    last_status VARCHAR(24) NOT NULL DEFAULT '',
    last_checked INT NOT NULL DEFAULT 0,
    last_consistent INT NOT NULL DEFAULT 0,
    last_pending INT NOT NULL DEFAULT 0,
    last_needs_review INT NOT NULL DEFAULT 0,
    last_conflict INT NOT NULL DEFAULT 0,
    last_unknown INT NOT NULL DEFAULT 0,
    last_reason TEXT NOT NULL DEFAULT ''
);
